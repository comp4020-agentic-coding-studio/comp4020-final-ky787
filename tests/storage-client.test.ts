import { afterEach, expect, it, vi } from 'vitest';
import { ProgressStore } from '../src/slice/storage.ts';
import { freshProgress } from '../src/slice/progress.ts';
afterEach(() => { vi.unstubAllGlobals(); vi.useRealTimers(); });
const savedResponse = (revision: number) => ({ ok: true, status: 200, json: async () => ({ revision, updatedAt: '2026-10-14T12:00:00Z' }) });
it('failed startup is visibly unsaved, without creating an accidental reset write', async () => {
    const fetch = vi.fn().mockRejectedValue(new Error('offline'));
    vi.stubGlobal('fetch', fetch);
    const store = new ProgressStore();
    expect(await store.load()).toBe(false);
    store.save(freshProgress());
    expect(store.ready).toBe(false);
    expect(store.status).toContain('unavailable');
    expect(fetch).toHaveBeenCalledTimes(1);
});
it('retries the newest logical state after a network failure', async () => {
    vi.useFakeTimers();
    const fetch = vi.fn().mockRejectedValueOnce(new Error('offline')).mockResolvedValue({ ok: true, status: 200, json: async () => ({ revision: 1, updatedAt: '2026-10-04T12:00:00Z' }) });
    vi.stubGlobal('fetch', fetch);
    const store = new ProgressStore();
    store.ready = true;
    store.save(freshProgress());
    await vi.waitFor(() => expect(store.status).toContain('pending'));
    const newer = freshProgress();
    newer.currentRoom = 'relay';
    store.save(newer);
    await vi.waitFor(() => expect(store.status).toBe('Saved on server'));
    expect(JSON.parse(fetch.mock.calls[1][1].body).progress.currentRoom).toBe('relay');
    expect(store.revision).toBe(1);
    await vi.advanceTimersByTimeAsync(3000);
    expect(fetch).toHaveBeenCalledTimes(2);
});
it('a conflicting tab blocks subsequent writes and asks for reload', async () => {
    const fetch = vi.fn().mockResolvedValue({ ok: false, status: 409 });
    vi.stubGlobal('fetch', fetch);
    const store = new ProgressStore();
    store.ready = true;
    store.save(freshProgress());
    await vi.waitFor(() => expect(store.conflict).toBe(true));
    store.save(freshProgress());
    expect(fetch).toHaveBeenCalledTimes(1);
    expect(store.status).toContain('another tab');
});
it('queues a full reset after an in-flight save with the acknowledged revision', async () => {
    let acknowledge!: (response: unknown) => void;
    const fetch = vi.fn().mockImplementationOnce(() => new Promise(resolve => { acknowledge = resolve; }))
        .mockResolvedValue({ ok: true, status: 200, json: async () => ({ revision: 9, updatedAt: '2026-10-05T12:00:00Z' }) });
    vi.stubGlobal('fetch', fetch);
    const store = new ProgressStore();
    store.ready = true; store.visitor = 'same-visitor'; store.revision = 7;
    const previous = freshProgress();
    previous.currentRoom = 'relay'; previous.completedRooms = ['pressure', 'switch'];
    previous.rooms.relay.switchB = true; previous.rooms.relay.checkpoint = 'relay';
    previous.mechanics = ['bridge'];
    previous.history = [{ room: 'relay', event: 'bridge', at: '2026-10-05T11:00:00Z' }];
    store.save(previous);
    store.save(freshProgress());
    expect(fetch).toHaveBeenCalledTimes(1);
    acknowledge({ ok: true, status: 200, json: async () => ({ revision: 8, updatedAt: '2026-10-05T11:00:00Z' }) });
    await vi.waitFor(() => expect(fetch).toHaveBeenCalledTimes(2));
    expect(JSON.parse(fetch.mock.calls[1][1].body)).toEqual({ revision: 8, progress: freshProgress() });
    expect(store.progress).toEqual(freshProgress());
    expect(store.visitor).toBe('same-visitor');
    expect(store.revision).toBe(9);
    expect(store.status).toBe('Saved on server');
});
it('reports unavailable startup without writing, and a ready clean store as saved', async () => {
    const fetch = vi.fn();
    vi.stubGlobal('fetch', fetch);
    const store = new ProgressStore();
    expect(await store.flush()).toBe(false);
    store.ready = true;
    expect(await store.flush()).toBe(true);
    expect(fetch).not.toHaveBeenCalled();
});
it('navigation callers await the current write and snapshots queued during later writes', async () => {
    const acknowledge: ((response: unknown) => void)[] = [];
    const fetch = vi.fn().mockImplementation(() => new Promise(resolve => acknowledge.push(resolve)));
    vi.stubGlobal('fetch', fetch);
    const store = new ProgressStore(); store.ready = true; store.revision = 7;
    store.save(freshProgress());
    let settled = false;
    const navigation = store.flush().then(saved => { settled = true; return saved; });
    const secondCaller = store.flush();
    const newer = freshProgress(); newer.currentRoom = 'relay';
    store.save(newer);
    expect(fetch).toHaveBeenCalledTimes(1);
    expect(settled).toBe(false);
    acknowledge[0](savedResponse(8));
    await vi.waitFor(() => expect(fetch).toHaveBeenCalledTimes(2));
    expect(JSON.parse(fetch.mock.calls[1][1].body)).toEqual({ revision: 8, progress: newer });
    expect(settled).toBe(false);
    const newest = freshProgress(); newest.currentRoom = 'uplink';
    store.save(newest);
    acknowledge[1](savedResponse(9));
    await vi.waitFor(() => expect(fetch).toHaveBeenCalledTimes(3));
    expect(JSON.parse(fetch.mock.calls[2][1].body)).toEqual({ revision: 9, progress: newest });
    expect(settled).toBe(false);
    acknowledge[2](savedResponse(10));
    expect(await navigation).toBe(true);
    expect(await secondCaller).toBe(true);
    expect(store.revision).toBe(10);
    expect(store.progress).toEqual(newest);
});
it('navigation reports a failed active write and preserves the newest snapshot for retry', async () => {
    vi.useFakeTimers();
    let fail!: (error: Error) => void;
    const fetch = vi.fn().mockImplementationOnce(() => new Promise((_resolve, reject) => { fail = reject; }))
        .mockResolvedValue(savedResponse(8));
    vi.stubGlobal('fetch', fetch);
    const store = new ProgressStore(); store.ready = true; store.revision = 7;
    store.save(freshProgress());
    const navigation = store.flush();
    const newest = freshProgress(); newest.currentRoom = 'relay';
    store.save(newest);
    fail(new Error('offline'));
    expect(await navigation).toBe(false);
    expect(fetch).toHaveBeenCalledTimes(1);
    expect(store.status).toContain('pending');
    await vi.advanceTimersByTimeAsync(3000);
    expect(fetch).toHaveBeenCalledTimes(2);
    expect(JSON.parse(fetch.mock.calls[1][1].body)).toEqual({ revision: 7, progress: newest });
    expect(await store.flush()).toBe(true);
    expect(store.status).toBe('Saved on server');
});
it('navigation reports an active-write conflict and never sends a queued overwrite', async () => {
    let acknowledge!: (response: unknown) => void;
    const fetch = vi.fn().mockImplementation(() => new Promise(resolve => { acknowledge = resolve; }));
    vi.stubGlobal('fetch', fetch);
    const store = new ProgressStore(); store.ready = true;
    store.save(freshProgress());
    const navigation = store.flush();
    const newest = freshProgress(); newest.currentRoom = 'relay';
    store.save(newest);
    acknowledge({ ok: false, status: 409 });
    expect(await navigation).toBe(false);
    expect(await store.flush()).toBe(false);
    store.save(newest);
    expect(fetch).toHaveBeenCalledTimes(1);
    expect(store.conflict).toBe(true);
    expect(store.status).toContain('another tab');
});
