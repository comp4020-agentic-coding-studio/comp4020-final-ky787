export function decodeXor(bytes: readonly number[]): string {
    return String.fromCharCode(...bytes.map(byte => byte ^ PRESENTATION_XOR_KEY));
}
/** Reveal original bytes deterministically; unfinished characters show their stored hex bytes. */
export function revealXor(bytes: readonly number[], fraction: number): string {
    const count = Math.floor(bytes.length * Math.max(0, Math.min(1, fraction)));
    return bytes.map((byte, index) => index < count ? String.fromCharCode(byte ^ PRESENTATION_XOR_KEY) : byte.toString(16).padStart(2, '0').toUpperCase()).join('');
}
